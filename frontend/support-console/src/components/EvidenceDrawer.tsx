import type { CSSProperties } from 'react'
import { EXPORT_ICON } from '../icons'
import { BUNDLE_INVOICE_LIMIT, RANGE_REASON, utcDay, type BundlePeriod, type BundlePreview, type StaffEntity } from '../auditApi'
import type { StaffTenant } from '../tenantsApi'
import { Drawer, MetaGrid } from './Drawer'
import { Note } from './Tenants'

export type EvidenceInputs = { tenant: string; entity: string; from: string; to: string }
type Retryable = { text: string; onRetry: () => void }

type Props = {
  inputs: EvidenceInputs
  onInputs: (patch: Partial<EvidenceInputs>) => void
  tenants: StaffTenant[]
  tenantsError?: Retryable
  /** Null until the tenant's companies have landed. */
  entities: StaffEntity[] | null
  entitiesError?: Retryable
  /** The preview of exactly these inputs; null while it reads or fails. */
  preview: BundlePreview | null
  previewLoading: boolean
  previewError?: Retryable
  busy: boolean
  onDownload: () => void
  onClose: () => void
}

const FIELD_INPUT: CSSProperties = { border: 0, outline: 'none', background: 'transparent', fontFamily: 'var(--font-sans)', fontSize: 13, color: 'var(--fg-1)', height: 30, flex: 1, minWidth: 0, padding: 0 }
const FIELD: CSSProperties = { marginBottom: 16 }
const LOCKED = { opacity: 0.45, filter: 'none', cursor: 'not-allowed' } as const

const periodLabel = (p: BundlePeriod): string => `${utcDay(p.from)} – ${utcDay(p.to)}`

// The app's block order (frontend/app/src/lib/evidenceBundleView.ts bundleBlockFor).
export function bundleReason(i: EvidenceInputs, p: BundlePreview | null): string | null {
  if (!i.entity) return 'Pick one company to export.'
  if (!i.from || !i.to) return 'Pick a period. A custom range needs both a start date and an end date.'
  if (i.from > i.to) return RANGE_REASON
  if (!p) return null
  if (p.counts.invoices === 0) return `No invoices were added to ${p.entity.name} in ${periodLabel(p.period)}, so there is nothing to export.`
  if (p.over_limit) return `${p.counts.invoices.toLocaleString('en-NG')} invoices is more than one bundle can hold. The limit is ${BUNDLE_INVOICE_LIMIT.toLocaleString('en-NG')}. Narrow the period and try again.`
  return null
}

export function EvidenceDrawer({ inputs, onInputs, tenants, tenantsError, entities, entitiesError, preview, previewLoading, previewError, busy, onDownload, onClose }: Props) {
  const reason = bundleReason(inputs, preview)
  const ready = preview !== null && reason === null && !busy
  return (
    <Drawer
      width={560}
      onClose={onClose}
      header={
        <>
          <div style={{ fontSize: 15, fontWeight: 600, marginBottom: 4 }}>Evidence bundle</div>
          <div style={{ fontSize: 12, color: 'var(--fg-3)', lineHeight: 1.5 }}>One company and one period: the file the tenant&apos;s admin downloads, generated by ASComply support.</div>
        </>
      }
      footer={
        <div style={{ flex: 1, display: 'flex', flexDirection: 'column', alignItems: 'flex-end', gap: 8 }}>
          <button type="button" onClick={onDownload} disabled={!ready} aria-describedby={reason ? 'evidence-reason' : undefined} className="ops-btn v2-btn v2-btn-primary" style={{ height: 38, ...(ready ? {} : LOCKED) }}>
            {EXPORT_ICON} Download bundle
          </button>
          {reason && (
            <div id="evidence-reason" style={{ fontSize: 12, lineHeight: 1.5, color: 'var(--fg-2)', textAlign: 'right' }}>
              {reason}
            </div>
          )}
        </div>
      }
    >
      <div style={FIELD}>
        <div className="label" style={{ marginBottom: 6 }}>
          Tenant
        </div>
        <select className="ops-input" aria-label="Tenant" value={inputs.tenant} onChange={(e) => onInputs({ tenant: e.target.value, entity: '' })} style={{ width: '100%' }}>
          <option value="">Choose a tenant</option>
          {tenants.map((t) => (
            <option key={t.id} value={t.id}>
              {t.name}
            </option>
          ))}
        </select>
        {tenantsError && <Note text={tenantsError.text} onRetry={tenantsError.onRetry} />}
      </div>

      <div style={FIELD}>
        <div className="label" style={{ marginBottom: 6 }}>
          Company
        </div>
        {entitiesError ? (
          <Note text={entitiesError.text} onRetry={entitiesError.onRetry} />
        ) : (
          <select className="ops-input" aria-label="Company" value={inputs.entity} disabled={!inputs.tenant || entities === null} onChange={(e) => onInputs({ entity: e.target.value })} style={{ width: '100%' }}>
            <option value="">{entities?.length === 0 ? 'No companies.' : 'Choose a company'}</option>
            {(entities ?? []).map((c) => (
              <option key={c.id} value={c.id}>
                {c.name}
              </option>
            ))}
          </select>
        )}
      </div>

      <div style={{ display: 'flex', gap: 12, ...FIELD }}>
        {(['from', 'to'] as const).map((k) => (
          <div key={k} style={{ flex: 1, minWidth: 0 }}>
            <div className="label" style={{ marginBottom: 6 }}>
              {k === 'from' ? 'From' : 'To'}
            </div>
            <div className="ops-input ops-field" style={{ display: 'flex', alignItems: 'center' }}>
              <input type="date" aria-label={k === 'from' ? 'From' : 'To'} value={inputs[k]} onChange={(e) => onInputs({ [k]: e.target.value })} style={FIELD_INPUT} />
            </div>
          </div>
        ))}
      </div>

      {preview && (
        <MetaGrid
          items={[
            { label: 'Company', value: preview.entity.name, mono: false },
            { label: 'TIN', value: preview.entity.tin ?? '—' },
            { label: 'Period', value: periodLabel(preview.period) },
            { label: 'Invoices', value: String(preview.counts.invoices) },
            { label: 'Line items', value: String(preview.counts.line_items) },
            { label: 'Status changes', value: String(preview.counts.status_transitions) },
            { label: 'Submissions', value: String(preview.counts.submissions) },
            { label: 'Exchange attempts', value: String(preview.counts.exchange_attempts) },
            { label: 'Body files', value: String(preview.counts.body_files) },
          ]}
        />
      )}
      {!preview && !reason && previewError && <Note text={previewError.text} onRetry={previewError.onRetry} />}
      {!preview && !reason && !previewError && previewLoading && <Note text="Reading the bundle preview…" />}
    </Drawer>
  )
}
